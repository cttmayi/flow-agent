/*
 * 代码审查工作流
 * 功能：获取当前分支的 git diff（与主分支对比），分析变更代码，输出 PR Review 格式报告
 * 流程：获取分支信息 → 收集 diff → 变更概览分析 → 逐文件审查 → 生成报告
 */

try {
  /* ======================== 阶段 1：获取分支与 diff 信息 ======================== */

  phase("获取分支与 Diff");

  const branchAndDiff = await agent(
    `请依次执行以下步骤，并按要求返回结果：

    步骤1：执行 git rev-parse --abbrev-ref HEAD 获取当前分支名
    步骤2：根据分支名判断 diff 范围：
      - 如果当前分支是 main 或 master，执行 git diff HEAD~1..HEAD 获取最近一次提交的变更
      - 否则执行 git merge-base main HEAD 获取与 main 的共同祖先，再执行 git diff <merge_base>..HEAD
    步骤3：执行 git diff --stat <范围> 获取变更统计信息
    步骤4：执行 git diff <范围> 获取完整 diff 内容

    返回格式（严格按此格式）：
    第一行：当前分支名
    第二行：变更统计（git diff --stat 的结果）
    空一行
    之后是完整的 git diff 内容`,
    { tools: ["bash"], timeout: 60000 }
  );

  const lines = branchAndDiff.split("\n");
  const currentBranch = lines[0]?.trim() || "unknown";
  const diffStat = lines[1]?.trim() || "";
  // 找到第一个空行之后的内容作为完整 diff
  const blankLineIndex = lines.findIndex((l, i) => i >= 2 && l.trim() === "");
  const diffContent = blankLineIndex >= 0
    ? lines.slice(blankLineIndex + 1).join("\n").trim()
    : lines.slice(2).join("\n").trim();

  // 如果没有 diff 内容，提前返回提示
  if (!diffContent) {
    return await agent(
      `当前分支 "${currentBranch}" 与主分支之间没有代码变更差异。\\n\\n` +
      `请生成一条友好的提示消息，说明以下情况：\\n` +
      `1. 当前分支与主分支相比没有检测到变更\\n` +
      `2. 可能的原因（如：刚创建分支、已合并、所有变更已提交到主分支等）\\n` +
      `3. 建议的操作（如：确认分支是否正确、提交代码后再运行等）\\n\\n` +
      `以 Markdown 格式输出。`,
      { tools: [], timeout: 15000 }
    );
  }

  /* ======================== 阶段 2：变更概览分析 ======================== */

  phase("分析变更概览");

  const checkpointKey = `review_overview_${currentBranch}`;
  const cachedOverview = checkpoint(checkpointKey);

  let overview;
  if (cachedOverview) {
    overview = cachedOverview;
  } else {
    overview = await agent(
      `以下是对比主分支后，当前分支 "${currentBranch}" 的代码变更：\\n\\n` +
      `## 变更统计\\n${diffStat}\\n\\n` +
      `## 完整 Diff\\n\`\`\`diff\\n${diffContent.slice(0, 8000)}\\n\`\`\`\\n\\n` +
      `请分析并返回以下内容（不要遗漏任何信息）：\\n` +
      `1. 变更涉及的文件列表（每个文件标注：文件名、变更类型【新增/修改/删除/重命名】）\\n` +
      `2. 每个文件的新增行数和删除行数（从 diff 中统计）\\n` +
      `3. 变更的总体范围和影响域描述（如：前端 UI 组件、后端 API 逻辑、数据库模型、配置文件、测试用例、基础设施等）\\n` +
      `4. 是否涉及破坏性变更（如 API 接口变更、数据库 schema 变更、配置格式变化等）`,
      { tools: [], timeout: 60000 }
    );
    checkpoint(checkpointKey, overview);
  }

  /* ======================== 阶段 3：逐文件深度审查 ======================== */

  phase("审查代码变更");

  const reviewDetails = await agent(
    `请对以下代码变更进行全面、深入的 Code Review。\\n\\n` +
    `## 分支信息\\n- 分支：${currentBranch}\\n- 统计：${diffStat}\\n\\n` +
    `## 变更概览\\n${overview}\\n\\n` +
    `## 完整 Diff\\n\`\`\`diff\\n${diffContent.slice(0, 12000)}\\n\`\`\`\\n\\n` +
    `### 审查维度（请逐维度检查，每个维度的发现按文件列出）：\\n\\n` +
    `1. **逻辑正确性**\\n` +
    `   - 是否存在算法或业务逻辑错误？\\n` +
    `   - 边界条件和极端情况是否处理？\\n` +
    `   - 条件判断和循环是否正确？\\n` +
    `   - 数据类型假设是否安全？\\n\\n` +
    `2. **安全性**\\n` +
    `   - 是否存在注入风险（SQL、NoSQL、命令、XSS）？\\n` +
    `   - 敏感信息（密钥、密码、Token、内网地址）是否暴露？\\n` +
    `   - 权限校验是否缺失或不正确？\\n` +
    `   - 输入验证和过滤是否充分？\\n\\n` +
    `3. **性能与资源**\\n` +
    `   - 是否存在不必要的循环或重复计算？\\n` +
    `   - 是否有内存泄漏或资源未释放风险？\\n` +
    `   - N+1 查询问题或冗余数据库调用？\\n` +
    `   - 大对象复制或频繁 GC 触发？\\n\\n` +
    `4. **代码质量与可维护性**\\n` +
    `   - 命名是否清晰且符合项目规范？\\n` +
    `   - 函数/方法是否过长或职责不单一？\\n` +
    `   - 是否有重复代码可提取复用？\\n` +
    `   - 注释和文档是否充分且准确？\\n` +
    `   - 代码格式化是否一致？\\n\\n` +
    `5. **错误处理与健壮性**\\n` +
    `   - 异常捕获是否恰当？\\n` +
    `   - 错误信息是否清晰且不泄露敏感信息？\\n` +
    `   - 是否有优雅的降级或重试策略？\\n` +
    `   - 异步操作的错误传递是否正确？\\n\\n` +
    `6. **测试覆盖**\\n` +
    `   - 变更是否包含对应测试？\\n` +
    `   - 测试是否覆盖关键路径和边界情况？\\n` +
    `   - 测试命名和结构是否清晰？\\n\\n` +
    `### 输出格式要求\\n` +
    `每个发现问题请按以下格式输出：\\n` +
    `【文件】${"`<文件路径>`"}${" 【行号】"}${"`<行号范围>`"}${" 【类型】"}${"<逻辑/安全/性能/质量/错误处理/测试>"}${" 【严重程度】"}${"<严重/中等/轻微>"}\\n` +
    `问题描述：（详细说明问题表现和潜在影响）\\n` +
    `修复建议：（给出具体的修复思路或代码示例）\\n` +
    `---`,
    { tools: [], timeout: 120000 }
  );

  /* ======================== 阶段 4：生成 PR Review 报告 ======================== */

  phase("生成 PR Review 报告");

  return await agent(
    `请将以下代码审查结果整理为专业的 PR Review 报告。\\n\\n` +
    `--- 上下文 ---\\n` +
    `分支：${currentBranch}\\n` +
    `变更统计：${diffStat}\\n\\n` +
    `--- 变更概览 ---\\n${overview}\\n\\n` +
    `--- 审查详情 ---\\n${reviewDetails}\\n\\n` +
    `请严格按照以下 Markdown 格式输出报告，每个章节必须完整：\\n\\n` +
    `# 📋 PR Review Report\\n\\n` +
    `---\\n\\n` +
    `## 📊 变更概览\\n` +
    `| 项目 | 内容 |\\n` +
    `|------|------|\\n` +
    `| 分支 | ${currentBranch} |\\n` +
    `| 统计 | ${diffStat.replace(/\|/g, '\\|')} |\\n` +
    `| 影响域 | （从 overview 中提取） |\\n` +
    `| 破坏性变更 | （是否涉及） |\\n\\n` +
    `### 变更文件清单\\n` +
    `（列出所有文件及变更类型，表格形式）\\n\\n` +
    `---\\n\\n` +
    `## 🔴 严重问题（必须修复）\\n` +
    `列出所有标记为"严重"的问题。\\n` +
    `每个问题包含：文件位置、问题描述、潜在影响、修复建议。\\n` +
    `如果没有严重问题，请写"本次变更未发现严重问题。"\\n\\n` +
    `---\\n\\n` +
    `## 🟡 改进建议（建议优化）\\n` +
    `列出所有标记为"中等"和"轻微"的问题。\\n` +
    `按文件分组，每个问题包含：问题描述、优化建议。\\n` +
    `如果没有改进建议，请写"本次变更代码质量良好，无特别改进建议。"\\n\\n` +
    `---\\n\\n` +
    `## ✅ 做得好的地方\\n` +
    `肯定代码中的亮点，至少列出 2-3 项：\\n` +
    `- 良好的设计模式或架构决策\\n` +
    `- 完善的错误处理或边界条件处理\\n` +
    `- 清晰的注释或文档\\n` +
    `- 充分的测试覆盖\\n` +
    `- 安全的编码实践\\n\\n` +
    `---\\n\\n` +
    `## 📝 总结与建议\\n` +
    `- 总体评价本次变更的质量\\n` +
    `- 是否建议合并（强烈建议合并 / 建议修复严重问题后合并 / 不建议合并需重大修改）\\n` +
    `- 后续改进方向或需关注的事项\\n\\n` +
    `---\\n\\n` +
    `## ⭐ 总体评分\\n` +
    `**评分：X / 5**\\n\\n` +
    `评分标准：\\n` +
    `- 5 分：代码完美，无任何问题\\n` +
    `- 4 分：代码良好，有少量轻微改进点\\n` +
    `- 3 分：代码一般，存在一些需关注的问题\\n` +
    `- 2 分：代码有较多问题，需较大改进\\n` +
    `- 1 分：代码存在严重问题，不建议合并\\n\\n` +
    `评分理由：（结合审查发现给出合理解释）\\n\\n` +
    `---\\n\\n` +
    `> 📌 本报告由 AI Code Review 工作流自动生成，请人工复核后决策。`,
    { tools: [], timeout: 60000 }
  );

} catch (err) {
  /* ======================== 容错处理 ======================== */
  return await agent(
    `代码审查工作流执行过程中发生错误：${err.message}\\n\\n` +
    `请生成友好的错误提示，包含：\\n` +
    `1. 错误可能的原因（如：不在 Git 仓库中、main 分支不存在、diff 对比失败、Agent 调用超时等）\\n` +
    `2. 建议的排查步骤\\n` +
    `   - 确认当前目录是否为 Git 仓库：git rev-parse --git-dir\\n` +
    `   - 确认 main 分支存在：git branch -a | grep main\\n` +
    `   - 确认有可对比的提交：git log --oneline -3\\n` +
    `3. 如何重新运行此工作流\\n\\n` +
    `以友好的 Markdown 格式输出。`,
    { tools: [], timeout: 30000 }
  );
}